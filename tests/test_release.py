"""Engineering checks against isolated fixtures, not learner-effect simulations."""
from __future__ import annotations

import hashlib
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
import zipfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from build_release import build_release
from release_core import SKILLS, check_release, verify_archive


class ReleaseTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.base = Path(self.temp.name)
        self.root = self.base / "project"
        self.root.mkdir()
        for name, text in {
            "README.md": "# Fixture\n[Entry](skills/learning-entry/SKILL.md)\n",
            "LICENSE": "Fixture license\n", "VERSION": "0.1.0\n", "AGENTS.md": "# Local guidance\n",
        }.items():
            self.write(name, text)
        for name in SKILLS:
            self.write(f"skills/{name}/SKILL.md", f"---\nname: {name}\ndescription: A bounded fixture skill.\n---\n# Method\n[Detail](references/detail.md)\n")
            self.write(f"skills/{name}/references/detail.md", "# Supporting method\n")
        self.entry = self.root / "skills/learning-entry/SKILL.md"

    def write(self, relative, text):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    def errors(self):
        return "\n".join(check_release(self.root).errors)

    def test_minimal_release_and_supported_markdown(self):
        self.write("docs/deep page.md", "# Page\n")
        self.write("README.md", '# Fixture\n[Page](<docs/deep page.md>)\n[Again][page]\n[page]: <docs/deep page.md>\n[Web](https://example.org)\n`[Example](missing.md)`\n```markdown\n[Code](missing.md)\n```\n')
        self.assertEqual([], check_release(self.root).errors)

    def test_illegal_name_and_empty_description(self):
        self.entry.write_text("---\nname: Illegal_Name\ndescription: ''\n---\n", encoding="utf-8")
        self.assertIn("name must match", self.errors())
        self.assertIn("description must", self.errors())

    def test_bad_link_and_undefined_reference(self):
        with self.entry.open("a", encoding="utf-8") as stream:
            stream.write("[Missing](references/no.md)\n[Undefined][no]\n")
        self.assertIn("missing or excluded relative link", self.errors())
        self.assertIn("missing-reference", self.errors())

    def test_cross_skill_and_external_release_dependency(self):
        for target in ("../concept-tutor/SKILL.md", "../../README.md", "../../../outside.md"):
            with self.subTest(target=target):
                original = self.entry.read_text(encoding="utf-8")
                self.entry.write_text(original + f"[Dependency]({target})\n", encoding="utf-8")
                self.assertIn("escapes skill boundary", self.errors())
                self.entry.write_text(original, encoding="utf-8")

    def test_machine_path_secret_scaffold_and_personal_data(self):
        probes = (
            ("Machine: " + "C:" + "/" + "Users" + "/someone/private.md", "machine-specific"),
            ("ghp" + "_" + "a" * 25, "potential private"),
            ("github_pat" + "_" + "a" * 25, "potential private"),
            ("sk" + "-" + "a" * 25, "potential private"),
            ("TO" + "DO: finish prose", "unfinished scaffold"),
        )
        for text, error in probes:
            with self.subTest(error=error):
                self.write("docs/leak.md", text)
                self.assertIn(error, self.errors())
        (self.root / "docs/leak.md").unlink()
        self.write("notes/private.md", "Personal learning evidence")
        self.assertIn("personal data", self.errors())

    def test_allowlist_and_reported_cache_exclusion(self):
        self.write(".git/config", "private git metadata")
        self.write("tools/__pycache__/module.pyc", "generated bytecode")
        self.write("dist/old.zip", "old release")
        report = check_release(self.root)
        self.assertEqual([], report.errors)
        self.assertEqual({".git", "dist", "tools/__pycache__"}, set(report.excluded))
        archive, _ = build_release(self.root, self.base / "output")
        with zipfile.ZipFile(archive) as packed:
            self.assertFalse(any(".git/" in name or "__pycache__" in name or "/dist/" in name for name in packed.namelist()))
        self.write("unexpected.txt", "not allowed at root")
        self.assertIn("not in release allowlist", self.errors())

    def test_intentional_workspace_templates_and_sensitive_names(self):
        self.write("skills/learning-method-workbench/templates/learning/state.md", "# Blank state template\n")
        self.assertEqual([], check_release(self.root).errors)
        self.write("templates/.env", "secret=value")
        self.assertIn("personal data or credential", self.errors())

    def test_symlink_and_junction_rejected(self):
        target = self.base / "outside"
        target.mkdir()
        link = self.root / "docs"
        try:
            link.symlink_to(target, target_is_directory=True)
        except OSError:
            if sys.platform != "win32":
                self.skipTest("Symlinks unavailable on this filesystem")
            # Directory junctions exercise Windows reparse handling without Developer Mode.
            result = subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(target)], capture_output=True, text=True)
            if result.returncode:
                self.skipTest("Neither symlinks nor Windows junctions are available")
        self.addCleanup(lambda: link.rmdir() if link.exists() and not link.is_symlink() else link.unlink(missing_ok=True))
        self.assertIn("symlink/reparse", self.errors())
        with self.assertRaises(ValueError):
            build_release(self.root, self.base / "output")

    def test_internal_output_and_existing_artifact_protection(self):
        with self.assertRaises(ValueError):
            build_release(self.root, self.root / "dist")
        archive, checksum = build_release(self.root, self.base / "output")
        previous = archive.read_bytes(), checksum.read_bytes()
        with self.assertRaises(FileExistsError):
            build_release(self.root, self.base / "output")
        self.assertEqual(previous, (archive.read_bytes(), checksum.read_bytes()))
        other = self.base / "checksum-only"
        other.mkdir()
        (other / archive.name).with_suffix(".zip.sha256").write_text("preserve", encoding="utf-8")
        with self.assertRaises(FileExistsError):
            build_release(self.root, other)
        self.assertFalse((other / archive.name).exists())

    def test_validation_prevents_build(self):
        self.write("README.md", "[Bad](missing.md)")
        output = self.base / "output"
        with self.assertRaises(ValueError):
            build_release(self.root, output)
        self.assertFalse(output.exists())

    def test_offline_extraction_and_independent_skill_copy(self):
        # Include the actual maintenance tools so an extracted release checks itself.
        tools = Path(__file__).resolve().parents[1] / "tools"
        for filename in ("release_core.py", "check_release.py", "build_release.py"):
            self.write("tools/" + filename, (tools / filename).read_text(encoding="utf-8"))
        archive, checksum = build_release(self.root, self.base / "output")
        self.assertEqual(hashlib.sha256(archive.read_bytes()).hexdigest(), checksum.read_text().split()[0])
        extract = self.base / "offline"
        with zipfile.ZipFile(archive) as packed:
            packed.extractall(extract)
        extracted = extract / "learning-foundation"
        result = subprocess.run([sys.executable, str(extracted / "tools/check_release.py")], cwd=self.base, capture_output=True, text=True)
        self.assertEqual(0, result.returncode, result.stdout + result.stderr)
        import shutil
        single = self.base / "single-skill"
        shutil.copytree(extracted / "skills/learning-entry", single)
        self.assertTrue((single / "SKILL.md").is_file())
        self.assertTrue((single / "references/detail.md").is_file())

    def test_zip_member_safety_and_inventory(self):
        for member in ("../escape.md", "/absolute.md", "learning-foundation/../../escape", "learning-foundation/back\\slash.md"):
            with self.subTest(member=member):
                archive = self.base / "unsafe.zip"
                with zipfile.ZipFile(archive, "w") as packed:
                    packed.writestr(member, b"unsafe")
                with self.assertRaises(ValueError):
                    verify_archive(archive, {member: hashlib.sha256(b"unsafe").hexdigest()})
        with zipfile.ZipFile(self.base / "extra.zip", "w") as packed:
            packed.writestr("learning-foundation/extra.md", "extra")
        with self.assertRaises(ValueError):
            verify_archive(self.base / "extra.zip", {})


if __name__ == "__main__":
    unittest.main()
